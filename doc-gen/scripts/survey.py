def build_index(files):
    """stem -> paths, every >=2-segment suffix -> paths, and the set of dirs.

    `index`, `__init__` and `mod` also register their parent directory, since
    that is the name other files import them by. Directories are indexed
    separately because Go, Java and C# import a package, not a file.
    """
    idx, suf, dirs = defaultdict(list), defaultdict(set), set()
    for rel in files:
        stem = posixpath.splitext(rel)[0]
        keys = [stem]
        parent = posixpath.dirname(stem)
        if parent:
            dirs.add(parent)
        if posixpath.basename(stem) in ("index", "__init__", "mod"):
            if parent:
                keys.append(parent)
        for k in keys:
            idx[k].append(rel)
            segs = k.split("/")
            for i in range(len(segs) - 1):
                suf["/".join(segs[i:])].add(rel)
    return idx, suf, dirs


RE_GO_MODULE = re.compile(r"^module\s+(\S+)", re.M)


def module_prefixes(texts):
    """Import prefix -> the directory it names, longest prefix first.

    A Go import is the module path plus the package directory, and a monorepo
    package is imported by its declared name. Both are stated exactly, in
    go.mod and package.json, so stripping them turns a long import path into a
    repo-relative directory with no guessing.
    """
    out = {}
    for rel, text in texts.items():
        if text is None:
            continue
        name = posixpath.basename(rel)
        base = posixpath.dirname(rel)
        if name == "go.mod":
            m = RE_GO_MODULE.search(text)
            if m:
                out[m.group(1)] = base
        elif name == "package.json":
            try:
                pkg = json.loads(text).get("name")
            except ValueError:
                continue
            if isinstance(pkg, str) and pkg:
                out[pkg] = base
    return sorted(out.items(), key=lambda kv: -len(kv[0]))


def strip_module_prefix(target, prefixes):
    """(target, was_internal). A stripped prefix proves the target is ours."""
    for prefix, base in prefixes:
        if target == prefix or target.startswith(prefix + "/"):
            rest = target[len(prefix):].lstrip("/")
            return (posixpath.join(base, rest) if base else rest) or base, True
    return target, False


def source_roots(files):
    roots = {""}
    for rel in files:
        segs = rel.split("/")[:-1]
        for i, s in enumerate(segs):
            if s in SOURCE_ROOT_NAMES:
                roots.add("/".join(segs[: i + 1]))
    return sorted(roots, key=lambda r: (r.count("/"), len(r)))[:MAX_ROOTS]


def resolve(target, is_rel, importer, idx, suf, dirs, roots):
    """What this import means: ("file", path), ("dir", path), or None.

    Ambiguity is treated as failure. A `utils` that could be six different
    files contributes nothing trustworthy to a fan-in count, and a wrong edge
    on an architecture diagram is worse than a missing one.

    A directory hit is a package import — Go, Java and C# name a package
    rather than a file — and is counted against the package, not spread over
    the files inside it.
    """
    t = posixpath.normpath(target)
    stem, ext = posixpath.splitext(t)
    if ext in STRIPPABLE_EXT:
        t = stem
    segs = [s for s in t.split("/") if s and s != "."]
    if not segs or ".." in segs:
        return None

    joined = "/".join(segs)
    cands = [joined]
    if not is_rel:
        d = posixpath.dirname(importer)
        if d:
            cands.append(d + "/" + joined)
        cands += [(r + "/" + joined if r else joined) for r in roots]
    for c in cands:
        hit = idx.get(c)
        if hit and len(hit) == 1 and hit[0] != importer:
            return "file", hit[0]
    for c in cands:
        if c in dirs and c != posixpath.dirname(importer):
            return "dir", c

    for i in range(len(segs) - 1):
        hit = suf.get("/".join(segs[i:]))
        if hit and len(hit) == 1:
            only = next(iter(hit))
            if only != importer:
                return "file", only
    return None


