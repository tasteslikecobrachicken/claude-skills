def score_of(rec):
    """Reading order, not importance. Importance needs the file's contents.

    Entry points come first because they are where a reader starts. Fan-in and
    churn are damped by log so one 400-importer utility module does not bury
    everything else. Tiny files are pushed down: a three-line barrel that
    re-exports a package collects enormous fan-in and teaches nobody anything.
    Depth breaks ties towards the top of the tree, where `main.go` beats
    `scripts/tools/gen/main.go`.
    """
    s = ROLE_W.get(rec["role"], 0.0)
    if rec["entry"]:
        s += 6.0
    s += 2.0 * math.log1p(rec["fan_in"])
    s += 1.2 * math.log1p(rec["pkg_fan_in"])
    s += 1.0 * math.log1p(rec["commits"])
    s -= 0.25 * rec["path"].count("/")
    if rec["lines"] < 8:
        s -= 2.0
    return round(s, 2)


ROLE_W = {
    "manifest": 2.5, "ci": 1.5, "build": 1.5, "source": 1.5, "infra": 1.0,
    "config": 0.5, "example": 0.3, "other": 0.0, "docs": 0.0, "test": -1.0,
}


def component(rel, depth):
    segs = rel.split("/")
    return "/".join(segs[:depth]) if len(segs) > depth else (
        "/".join(segs[:-1]) or "(root)"
    )


def dir_component(d, depth):
    return "/".join(d.split("/")[:depth]) if d else "(root)"


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("paths", nargs="*", default=["."],
                    help="limit the survey to these paths, relative to --root "
                         "(default: whole repo)")
    ap.add_argument("--root", default=".", help="repo root (default: cwd)")
    ap.add_argument("--top", type=int, default=40,
                    help="how many ranked files to report; 0 for all")
    ap.add_argument("--depth", type=int, default=2,
                    help="path depth that counts as one component (default: 2)")
    ap.add_argument("--days", type=int, default=365,
                    help="churn window in days (default: 365)")
    ap.add_argument("--no-git", action="store_true",
                    help="skip git; no churn data")
    ap.add_argument("--text", action="store_true", help="human-readable output")
    args = ap.parse_args()

    root = str(Path(args.root).resolve())
    files = None if args.no_git else git_files(root)
    in_git = files is not None
    if not in_git:
        files = walked_files(root)

    scopes = []
    for p in args.paths:
        full = Path(p) if os.path.isabs(p) else Path(root) / p
        scopes.append(os.path.relpath(str(full.resolve()), root).replace(os.sep, "/"))
    if scopes and set(scopes) != {"."}:
        files = [f for f in files
                 if any(f == s or f.startswith(s + "/") for s in scopes)]

    kept, texts = [], {}
    skipped, examples = Counter(), defaultdict(list)
    for rel in sorted(files):
        reason = skip_reason(root, rel)
        text = None
        if not reason:
            text, reason = read_text(os.path.join(root, rel))
            if text is not None:
                reason = content_skip(rel, text)
        if reason:
            skipped[reason] += 1
            if len(examples[reason]) < 4:
                examples[reason].append(rel)
            continue
        kept.append(rel)
        texts[rel] = text

    roots = source_roots(kept)
    roots_set = set(roots)
    idx, suf, dirs = build_index(kept)
    prefixes = module_prefixes(texts)

    declared = set()
    for rel in kept:
        if posixpath.basename(rel) == "package.json":
            for t in package_json_entries(root, rel):
                hit = idx.get(posixpath.splitext(t)[0]) or idx.get(t)
                if hit:
                    declared.add(hit[0])

    fan_in, pkg_fan_in = Counter(), Counter()
    importers = defaultdict(list)
    externals = Counter()
    edges = Counter()
    unresolved = 0

    for rel, text in texts.items():
        fam = CODE_FAMILY.get(posixpath.splitext(rel)[1].lower())
        if not fam or text is None:
            continue
        seen = set()
        for raw in extract_imports(fam, text):
            norm = normalize_target(raw, fam, rel)
            if not norm:
                continue
            target, is_rel = norm
            if not is_rel:
                target, internal = strip_module_prefix(target, prefixes)
                is_rel = is_rel or internal
            hit = resolve(target, is_rel, rel, idx, suf, dirs, roots)
            if not hit:
                if is_rel:
                    unresolved += 1
                else:
                    name = external_name(target, fam)
                    if name:
                        externals[name] += 1
                continue
            kind, dest = hit
            if dest in seen:
                continue
            seen.add(dest)
            if kind == "file":
                fan_in[dest] += 1
                if len(importers[dest]) < 8:
                    importers[dest].append(rel)
                cb = component(dest, args.depth)
            else:
                pkg_fan_in[dest] += 1
                cb = dir_component(dest, args.depth)
            ca = component(rel, args.depth)
            if ca != cb:
                edges[(ca, cb)] += 1

    commits, last = (churn(root, args.days) if in_git and not args.no_git
                     else (Counter(), {}))

    records, langs, roles = [], Counter(), Counter()
    comps = defaultdict(lambda: {"files": 0, "lines": 0, "langs": Counter()})
    for rel in kept:
        name = posixpath.basename(rel)
        ext = posixpath.splitext(name)[1].lower()
        text = texts[rel]
        role = role_of(rel, name, ext)
        lang = EXT_LANG.get(ext, ext.lstrip(".") or name)
        reason = entry_reason(rel, roots_set)
        if rel in declared:
            reason = "declared in package.json"
        rec = {
            "path": rel,
            "role": role,
            "lang": lang,
            "lines": text.count("\n") + 1 if text else 0,
            "fan_in": fan_in.get(rel, 0),
            "pkg_fan_in": pkg_fan_in.get(posixpath.dirname(rel), 0),
            "importers": importers.get(rel, []),
            "commits": commits.get(rel, 0),
            "last_change": last.get(rel),
            "entry": bool(reason),
            "entry_reason": reason,
        }
        rec["score"] = score_of(rec)
        records.append(rec)
        roles[role] += 1
        c = comps[component(rel, args.depth)]
        c["files"] += 1
        c["lines"] += rec["lines"]
        if role in ("source", "test") and ext in EXT_LANG:
            langs[lang] += 1
            c["langs"][lang] += 1

    records.sort(key=lambda r: (-r["score"], r["path"]))
    ranked = records if args.top <= 0 else records[: args.top]

    result = {
        "root": root,
        "git": in_git,
        "counts": {
            "kept": len(kept),
            "skipped": sum(skipped.values()),
            "lines": sum(r["lines"] for r in records),
            "resolved_imports": sum(fan_in.values()),
            "resolved_package_imports": sum(pkg_fan_in.values()),
            "unresolved_relative": unresolved,
        },
        "last_commit": (run_git(["git", "-C", root, "log", "-1", "--format=%cs"])
                        or "").strip() or None,
        "skipped_detail": {k: {"files": v, "examples": examples[k]}
                           for k, v in skipped.most_common()},
        "languages": langs.most_common(15),
        "roles": roles.most_common(),
        "source_roots": [r or "(root)" for r in roots[:12]],
        "entry_points": [{"path": r["path"], "why": r["entry_reason"]}
                         for r in records if r["entry"]],
        "manifests": [r["path"] for r in records if r["role"] == "manifest"],
        "ci": [r["path"] for r in records if r["role"] in ("ci", "infra", "build")],
        "existing_docs": [r["path"] for r in records if r["role"] == "docs"][:60],
        "existing_docs_total": sum(1 for r in records if r["role"] == "docs"),
        "components": sorted(
            ({"name": k, "files": v["files"], "lines": v["lines"],
              "langs": v["langs"].most_common(3)} for k, v in comps.items()),
            key=lambda c: -c["lines"],
        ),
        "edges": [{"from": a, "to": b, "count": n}
                  for (a, b), n in edges.most_common(60)],
        "external_imports": externals.most_common(25),
        "ranked": ranked,
    }

    if not args.text:
        json.dump(result, sys.stdout, indent=2)
        sys.stdout.write("\n")
        return

    c = result["counts"]
    langs_str = ", ".join(f"{n} {name}" for name, n in result["languages"][:6])
    print(f"{c['kept']} files kept, {c['skipped']} skipped · "
          f"{c['lines']:,} lines · {langs_str}")
    if result["last_commit"]:
        print(f"last commit {result['last_commit']}")
    if not in_git:
        print("not a git repo: no churn data, and ignored paths are only "
              "excluded by name", file=sys.stderr)

    print(f"\n--- entry points ({len(result['entry_points'])}) ---")
    for e in result["entry_points"][:20]:
        print(f"  {e['path']:<50} {e['why']}")

    print("\n--- manifests, CI, infra ---")
    for p in (result["manifests"] + result["ci"])[:25]:
        print(f"  {p}")

    print(f"\n--- components (depth {args.depth}) ---")
    for comp in result["components"][:20]:
        langs_c = "/".join(n for n, _ in comp["langs"]) or "-"
        print(f"  {comp['name']:<34} {comp['files']:>5} files "
              f"{comp['lines']:>8,} lines  {langs_c}")

    print("\n--- component edges (importer -> imported) ---")
    for e in result["edges"][:25]:
        print(f"  {e['from']:<30} -> {e['to']:<30} {e['count']:>4}")

    print(f"\n--- read first ({len(ranked)}) ---")
    for i, r in enumerate(ranked, 1):
        why = []
        if r["entry"]:
            why.append("entry")
        if r["fan_in"]:
            why.append(f"fan-in {r['fan_in']}")
        if r["pkg_fan_in"]:
            why.append(f"pkg fan-in {r['pkg_fan_in']}")
        if r["commits"]:
            why.append(f"{r['commits']} commits")
        print(f"{i:>4} {r['score']:>6}  {r['path']:<46} {r['lang']:<11} "
              f"{r['lines']:>6}L  {', '.join(why)}")

    print("\n--- most-imported externals (includes stdlib) ---")
    print("  " + ", ".join(f"{n} ({k})" for n, k in result["external_imports"][:15]))

    if result["existing_docs"]:
        print(f"\n--- existing docs ({result['existing_docs_total']}) ---")
        for p in result["existing_docs"][:20]:
            print(f"  {p}")

    if result["skipped_detail"]:
        print("\n--- skipped ---")
        for reason, info in result["skipped_detail"].items():
            print(f"  {info['files']:>6}  {reason}: "
                  f"{', '.join(info['examples'][:3])}")


if __name__ == "__main__":
    main()
