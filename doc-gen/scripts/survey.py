def role_of(rel, name, ext):
    parts = rel.split("/")
    dirs = parts[:-1]
    if name in MANIFESTS or ext in (".csproj", ".fsproj", ".vbproj"):
        return "manifest"
    if name in CI_FILES or (parts[0] == ".github" and "workflows" in dirs):
        return "ci"
    if parts[0] in (".circleci", ".buildkite", ".woodpecker"):
        return "ci"
    if any(d in TEST_DIRS for d in dirs) or TEST_NAME.search(name):
        return "test"
    # A docs/ directory can be a whole site (Hugo, Docusaurus). Its prose is
    # documentation; its JavaScript is source code.
    if ext in PROSE_EXT or (parts[0] in DOC_DIRS and ext not in CODE_FAMILY):
        return "docs"
    if name.startswith("Dockerfile") or name in INFRA_FILES or ext in (".tf", ".tfvars"):
        return "infra"
    if name in BUILD_FILES or BUILD_NAME.search(name):
        return "build"
    if parts[0] in ("examples", "example", "samples", "demo", "demos"):
        return "example"
    if ext in EXT_LANG and ext not in PROSE_EXT and ext not in (
        ".yml", ".yaml", ".json", ".toml"
    ):
        return "source"
    if ext in (".yml", ".yaml", ".json", ".toml", ".ini", ".cfg", ".conf",
               ".properties", ".env") or name.startswith("."):
        return "config"
    return "other"


def entry_reason(rel, roots_set):
    parts = rel.split("/")
    name = parts[-1]
    stem, ext = posixpath.splitext(name)
    if name in ENTRY_NAMES:
        return "conventional name"
    if stem == "index" and ext in (".js", ".jsx", ".ts", ".tsx", ".mjs"):
        return "package index" if posixpath.dirname(rel) in roots_set else None
    if len(parts) > 1 and parts[-2] in ("bin", "cmd") and ext in (
        ".rs", ".go", ".js", ".ts", ".py"
    ):
        return "under bin/ or cmd/"
    return None


def package_json_entries(root, rel):
    """Files named as `main`, `module` or `bin` by a package.json."""
    try:
        data = json.loads(Path(root, rel).read_text(encoding="utf-8", errors="replace"))
    except (OSError, ValueError):
        return []
    base = posixpath.dirname(rel)
    targets = []
    for key in ("main", "module"):
        if isinstance(data.get(key), str):
            targets.append(data[key])
    binv = data.get("bin")
    if isinstance(binv, str):
        targets.append(binv)
    elif isinstance(binv, dict):
        targets += [v for v in binv.values() if isinstance(v, str)]
    return [posixpath.normpath(posixpath.join(base, t)) for t in targets]


