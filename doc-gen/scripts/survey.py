#!/usr/bin/env python3
"""Decide which files in a repo are worth reading, and in what order.

Documenting a codebase means reading it, and no one can read forty thousand
files. Most of them are not even the project: vendored dependencies, build
output, generated clients, minified bundles, lockfiles. Those have to go first,
because a survey that reports `node_modules` as the largest component is worse
than no survey.

What survives still needs an order. This script produces one from four
mechanical signals:

  entry points   where execution starts, by convention and by manifest
  fan-in         how many files in the repo import this one
  churn          commits touching it in the recent window
  role           source, manifest, CI, infra, test, docs

plus the import edges between directories, which are the raw material for a
component diagram — an edge here means one file really imports another, not
that two names sound related.

Nothing here decides what the code *does*, which parts are public, or what
belongs in the documentation. Those come from reading the files this script
puts at the top; see SKILL.md.

Known limits, by design: import extraction is regex over text, not parsing. It
resolves a target to a file only when the match is unambiguous, so fan-in
undercounts in repos with heavy aliasing, dependency injection, dynamic imports
or build-time path mapping. Reflection, plugin registries and DI containers are
invisible to it. A file with fan-in 0 is not necessarily dead — it may be
reached by a route table, a config string, or a framework's autoloader.
"""

