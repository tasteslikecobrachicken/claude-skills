def run_git(args, timeout=60):
    try:
        out = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout if out.returncode == 0 else None


def git_files(root):
    out = run_git(["git", "-C", root, "ls-files", "-z", "--cached", "--others",
                   "--exclude-standard"])
    return None if out is None else [f for f in out.split("\0") if f]


def walked_files(root):
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
        for f in filenames:
            rel = os.path.relpath(os.path.join(dirpath, f), root)
            out.append(rel.replace(os.sep, "/"))
    return out


def skip_reason(root, rel):
    parts = rel.split("/")
    if any(p in EXCLUDE_DIRS for p in parts[:-1]):
        return "vendored-or-build"
    name = parts[-1]
    if name in LOCKFILES:
        return "lockfile"
    if GENERATED_NAMES.search(name):
        return "generated"
    try:
        if os.path.getsize(os.path.join(root, rel)) > MAX_BYTES:
            return "too-large"
    except OSError:
        return "unreadable"
    return None


def read_text(full):
    try:
        raw = open(full, "rb").read()
    except OSError:
        return None, "unreadable"
    if b"\0" in raw[:8000]:
        return None, "binary"
    return raw.decode("utf-8", errors="replace"), None


def content_skip(rel, text):
    for line in text.split("\n", 30)[:30]:
        if GENERATED_BANNER.search(line):
            return "generated"
    if posixpath.splitext(rel)[1].lower() in MINIFIABLE:
        if any(len(line) > 500 for line in text.split("\n", 50)[:50]):
            return "minified"
    return None


def churn(root, days):
    """commits touching each file in the window, and when it last changed."""
    out = run_git(["git", "-C", root, "log", f"--since={days}.days.ago",
                   "--pretty=format:%x01%cs", "--name-only"], timeout=120)
    counts, last = Counter(), {}
    if not out:
        return counts, last
    stamp = None
    for line in out.splitlines():
        if line.startswith("\x01"):
            stamp = line[1:]
        elif line.strip():
            p = line.strip()
            counts[p] += 1
            last.setdefault(p, stamp)
    return counts, last


