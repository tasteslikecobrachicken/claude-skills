#!/usr/bin/env python3
"""Collect TODO-style markers that are genuinely comments, and nothing else.

A grep for TODO returns three kinds of thing: notes somebody left in a comment,
identifiers that happen to contain the word, and the word appearing in data —
string literals, lint configs, test fixtures, docs about the convention. Only
the first is a task. Telling them apart needs to know where comments start and
stop in the file's language, which is why this is a script and not a regex.

So: per-language comment/string scanning, plus the file-level exclusions
(generated, minified, vendored, lockfiles) that no amount of line matching can
do. Markers are grouped into clusters by normalized text, and dated by
`git blame`, because duplicates and age are mechanical facts.

Nothing here decides whether a marker matters. Whether the claim is still true,
how severe it is, and what to fix first are judgements for the caller; see
SKILL.md. The scanner's only job is to hand over a list worth reading.

Known limits, by design: the scanner is lexical, not a parser. It does not know
about heredocs, nested block comments, or languages absent from SPECS (those
are scanned with a guessed syntax and tagged `syntax: guessed`). A marker in a
comment that is itself commented-out code looks like any other marker.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

DEFAULT_MARKERS = (
    "TODO", "FIXME", "HACK", "XXX", "BUG", "OPTIMIZE", "REFACTOR", "DEPRECATED",
)

# Files large enough that a marker in them is not the point. Also keeps the
# character-level scanner off multi-megabyte data files.
MAX_BYTES = 2_000_000

EXCLUDE_DIRS = frozenset(
    """.git node_modules bower_components vendor third_party Pods .venv venv
    __pycache__ .tox .mypy_cache .pytest_cache dist build out target .next
    .nuxt .output coverage .terraform .gradle .idea .vscode""".split()
)

LOCKFILES = frozenset(
    """package-lock.json yarn.lock pnpm-lock.yaml npm-shrinkwrap.json Cargo.lock
    poetry.lock Pipfile.lock Gemfile.lock composer.lock go.sum flake.lock""".split()
)

# Names that are generated by convention, so the banner check never has to run.
GENERATED_NAMES = re.compile(
    r"""(\.min\.[a-z]+$|\.map$|_pb2(_grpc)?\.pyi?$|\.pb\.(go|cc|h)$|
         \.g\.dart$|\.freezed\.dart$|\.generated\.[a-z]+$|\.designer\.cs$|
         \.snap$|^.*\.lock$)""",
    re.X,
)

GENERATED_BANNER = re.compile(
    r"DO NOT EDIT|@generated|Code generated by|auto-?generated|autogenerated", re.I
)

# Minification only happens to these. Applying a long-line test more widely
# would throw out Markdown and text files, where one unwrapped paragraph per
# line is normal and a TODO on it is perfectly real.
MINIFIABLE = frozenset(".js .mjs .cjs .jsx .ts .tsx .css .scss .html .svg".split())

PROSE_EXT = frozenset(".md .markdown .rst .txt .adoc .org".split())

TICKET = re.compile(r"\b([A-Z][A-Z0-9]+-\d+)\b|(?<![\w&])#(\d{2,6})\b")
OWNER = re.compile(r"^[(\[]([^)\]]{1,40})[)\]]|^\s*@([A-Za-z0-9_.-]+)")


# --------------------------------------------------------------------------
# language syntax


class Spec:
    """Where comments and strings begin and end in one family of languages.

    `strings` carries a multiline flag per delimiter. Single-line strings are
    force-closed at the newline: an apostrophe in prose ("don't") or a lone
    quote in a regex would otherwise desync the scanner and swallow the rest of
    the file, hiding every marker below it. Self-healing per line is worth more
    than exactness on the rare multi-line case.
    """

    __slots__ = ("line", "block", "strings")

    def __init__(self, line=(), block=(), strings=()):
        self.line, self.block, self.strings = line, block, strings


C = Spec(("//",), (("/*", "*/"),), (('"', False), ("'", False)))
CJS = Spec(("//",), (("/*", "*/"),), (('"', False), ("'", False), ("`", True)))
HASH = Spec(("#",), (), (('"', False), ("'", False)))
PY = Spec(("#",), (), (('"""', True), ("'''", True), ('"', False), ("'", False)))
SQL = Spec(("--",), (("/*", "*/"),), (("'", False), ('"', False)))
LUA = Spec(("--",), (("--[[", "]]"),), (('"', False), ("'", False)))
MARKUP = Spec((), (("<!--", "-->"),), ())
CSS = Spec((), (("/*", "*/"),), (('"', False), ("'", False)))
LISP = Spec((";",), (), (('"', False),))
PCT = Spec(("%",), (), ())
GUESS = Spec(("#", "//"), (("/*", "*/"),), (('"', False), ("'", False)))

SPECS = {}
for _exts, _spec in (
    (".c .h .cpp .cc .cxx .hpp .hh .cs .java .kt .kts .scala .swift .rs .dart "
     ".groovy .m .mm .php .proto .glsl .sol .zig .v", C),
    (".js .mjs .cjs .jsx .ts .tsx .go .json5 .jsonc", CJS),
    (".sh .bash .zsh .fish .rb .pl .pm .r .yml .yaml .toml .ini .cfg .conf .tf "
     ".tfvars .ex .exs .nix .jl .gitignore .dockerignore .env", HASH),
    (".py .pyi", PY),
    (".sql .hs .elm .adb .ads", SQL),
    (".lua", LUA),
    (".html .htm .xml .xhtml .vue .svelte .svg .md .markdown .rst .txt .adoc "
     ".org .plist .xaml", MARKUP),
    (".css .scss .sass .less .styl", CSS),
    (".el .lisp .clj .cljs .cljc .edn .scm .rkt .asm .s", LISP),
    (".tex .erl .hrl .mat", PCT),
):
    for _e in _exts.split():
        SPECS[_e] = _spec

# Extensionless files people actually leave TODOs in.
SPECS_BY_NAME = {
    "Makefile": HASH, "makefile": HASH, "GNUmakefile": HASH, "Dockerfile": HASH,
    "Rakefile": HASH, "Gemfile": HASH, "Vagrantfile": HASH, "Justfile": HASH,
    "justfile": HASH, "Brewfile": HASH, "CMakeLists.txt": HASH,
}


def spec_for(path):
    """Return (spec, guessed). Unknown types are still scanned, but flagged."""
    name = os.path.basename(path)
    if name in SPECS_BY_NAME:
        return SPECS_BY_NAME[name], False
    ext = os.path.splitext(name)[1].lower()
    if ext in SPECS:
        return SPECS[ext], False
    return GUESS, True


# --------------------------------------------------------------------------
# scanning


def regions(text, spec):
    """Every comment and string span in the file, as (kind, start, end).

    One pass, jumping between candidate delimiters rather than walking each
    character. Alternatives are sorted longest-first so `\"\"\"` wins over `\"`
    and `--[[` over `--`.
    """
    toks = {}
    for open_, close in spec.block:
        toks[open_] = ("comment", close, True)
    for tok in spec.line:
        toks.setdefault(tok, ("comment", "\n", False))
    for delim, multi in spec.strings:
        toks.setdefault(delim, ("string", delim, multi))
    if not toks:
        return []

    pat = re.compile("|".join(re.escape(t) for t in sorted(toks, key=len, reverse=True)))
    out, i, n = [], 0, len(text)
    while i < n:
        m = pat.search(text, i)
        if not m:
            break
        kind, close, multi = toks[m.group(0)]
        start = m.start()
        body = start + len(m.group(0))
        if kind == "comment":
            if close == "\n":
                end = text.find("\n", body)
                end = n if end < 0 else end
            else:
                end = text.find(close, body)
                end = n if end < 0 else end + len(close)
        else:
            end = close_string(text, body, close, multi)
            # A triple-quoted string opening its own line is a Python
            # docstring: documentation, and a normal place to leave a marker.
            # Mid-expression triple quotes are data and stay strings.
            if len(m.group(0)) >= 3 and not text[text.rfind("\n", 0, start) + 1:start].strip():
                kind = "docstring"
        out.append((kind, start, end))
        i = max(end, start + 1)
    return out


def close_string(text, i, delim, multi):
    n = len(text)
    while i < n:
        c = text[i]
        if c == "\\":
            i += 2
            continue
        if not multi and c == "\n":
            return i  # unterminated on its line: assume it was never a string
        if text.startswith(delim, i):
            return i + len(delim)
        i += 1
    return n


def region_at(regs, offset):
    for kind, start, end in regs:
        if start <= offset < end:
            return kind, end
        if start > offset:
            break
    return "code", None


def note_text(text, start, end):
    """The marker's note: to end of line, minus comment scaffolding."""
    eol = text.find("\n", start)
    stop = min(eol if eol >= 0 else len(text), end or len(text))
    note = text[start:stop]
    note = re.sub(r"(\*/|-->|\]\]|\"\"\"|''')\s*$", "", note)
    return " ".join(note.split())[:300]


def normalize(note, marker):
    """Cluster key: the note's shape, ignoring the marker word, punctuation,
    owners, ticket ids and any specific number. `remove after node 18` and
    `remove after Node 20` are the same intent and should cluster."""
    s = note[len(marker):] if note.startswith(marker) else note
    s = OWNER.sub(" ", s.strip())
    s = TICKET.sub(" ", s)
    s = re.sub(r"\d+", "#", s.lower())
    s = re.sub(r"[^a-z0-9#]+", " ", s)
    return " ".join(s.split())


def scan_file(path, text, marker_re):
    spec, guessed = spec_for(path)
    regs = regions(text, spec)
    prose = os.path.splitext(path)[1].lower() in PROSE_EXT
    found, rejected = [], Counter()

    for m in marker_re.finditer(text):
        start = m.start("mark")
        kind, end = region_at(regs, start)
        # A prose file has no comments — all of it is text — so the
        # comment test would throw away every real checklist item. Keep the
        # markers and let the caller judge task from mention.
        if not prose and kind not in ("comment", "docstring"):
            rejected[kind] += 1
            continue
        note = note_text(text, start, end)
        marker = m.group("mark")
        tail = note[len(marker):]
        owner = OWNER.match(tail)
        found.append(
            {
                "path": path,
                "line": text.count("\n", 0, start) + 1,
                "marker": marker,
                "note": note,
                "context": "prose" if prose else ("docstring" if kind == "docstring" else "code"),
                "syntax": "guessed" if guessed else "known",
                "owner": next((g for g in owner.groups() if g), None) if owner else None,
                "tickets": sorted({g for t in TICKET.findall(note) for g in t if g}),
                "key": normalize(note, marker),
            }
        )
    return found, rejected


# --------------------------------------------------------------------------
# file selection


def git_files(root):
    """Tracked files plus untracked ones git isn't ignoring.

    Tracked-only would silently scan nothing in a repo whose work has not been
    committed yet, and report it as a clean bill of health. `--exclude-standard`
    still honours .gitignore, which is where the build output exclusion comes
    from.
    """
    try:
        out = subprocess.run(
            ["git", "-C", root, "ls-files", "-z", "--cached", "--others",
             "--exclude-standard"],
            capture_output=True, text=True, timeout=60,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0:
        return None
    return [f for f in out.stdout.split("\0") if f]


def walked_files(root):
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
        for f in filenames:
            out.append(os.path.relpath(os.path.join(dirpath, f), root))
    return out


def skip_reason(root, rel):
    """Why this file cannot hold a task, or None. Order is cheapest-first."""
    parts = rel.split(os.sep)
    if any(p in EXCLUDE_DIRS for p in parts[:-1]):
        return "vendored-or-build"
    name = parts[-1]
    if name in LOCKFILES or GENERATED_NAMES.search(name):
        return "generated"

    full = os.path.join(root, rel)
    try:
        size = os.path.getsize(full)
    except OSError:
        return "unreadable"
    if size > MAX_BYTES:
        return "too-large"
    return None


def read_text(full):
    try:
        raw = open(full, "rb").read()
    except OSError:
        return None, "unreadable"
    if b"\0" in raw[:8000]:
        return None, "binary"
    return raw.decode("utf-8", errors="replace"), None


def content_skip(rel, text):
    head = text.split("\n", 40)[:40]
    for line in head:
        if GENERATED_BANNER.search(line):
            return "generated"
    if os.path.splitext(rel)[1].lower() in MINIFIABLE:
        if any(len(line) > 500 for line in text.split("\n", 50)[:50]):
            return "minified"
    return None


# --------------------------------------------------------------------------
# blame


def blame_file(root, rel, lines):
    """author/date per marker line. One `git blame` call, many -L ranges."""
    cmd = ["git", "-C", root, "blame", "--line-porcelain"]
    for ln in lines[:200]:
        cmd += ["-L", f"{ln},{ln}"]
    cmd += ["--", rel]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return {}
    if out.returncode != 0:
        return {}

    info, cur, header = {}, {}, re.compile(r"^([0-9a-f]{40}) \d+ (\d+)")
    for line in out.stdout.splitlines():
        m = header.match(line)
        if m:
            cur = {"line": int(m.group(2)), "uncommitted": m.group(1) == "0" * 40}
        elif line.startswith("author "):
            cur["author"] = line[7:]
        elif line.startswith("author-time "):
            cur["time"] = int(line[12:])
        elif line.startswith("\t") and cur.get("line"):
            info[cur["line"]] = cur
            cur = {}
    return info


def attach_blame(root, markers):
    by_file = defaultdict(list)
    for mk in markers:
        by_file[mk["path"]].append(mk)
    now = time.time()
    for path, group in by_file.items():
        info = blame_file(root, path, sorted(mk["line"] for mk in group))
        for mk in group:
            got = info.get(mk["line"])
            if not got or got.get("uncommitted") or not got.get("time"):
                continue
            mk["author"] = got.get("author")
            mk["date"] = time.strftime("%Y-%m-%d", time.localtime(got["time"]))
            mk["age_days"] = int((now - got["time"]) // 86400)


# --------------------------------------------------------------------------


def cluster(markers):
    """Markers sharing a normalized note. Copy-paste and one-missing-abstraction
    both land here; which one it is takes reading the sites, not the key."""
    groups = defaultdict(list)
    for mk in markers:
        if mk["key"]:
            groups[mk["key"]].append(mk)
    out = [
        {
            "key": key,
            "count": len(g),
            "files": len({mk["path"] for mk in g}),
            "example": g[0]["note"],
            "sites": [f"{mk['path']}:{mk['line']}" for mk in g],
        }
        for key, g in groups.items()
        if len(g) > 1
    ]
    out.sort(key=lambda c: (-c["count"], c["key"]))
    return out


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("paths", nargs="*", default=["."],
                    help="files or directories to scan, relative to --root "
                         "(default: whole repo)")
    ap.add_argument("--root", default=".", help="repo root (default: cwd)")
    ap.add_argument("--markers", default="",
                    help="comma-separated extra markers, e.g. WIP,REVISIT")
    ap.add_argument("--no-blame", action="store_true",
                    help="skip git blame; faster, but no age or author")
    ap.add_argument("--text", action="store_true", help="human-readable output")
    args = ap.parse_args()

    root = str(Path(args.root).resolve())
    words = list(DEFAULT_MARKERS) + [
        w.strip() for w in args.markers.split(",") if w.strip()
    ]
    # Bounded by non-word characters so identifiers never match: TODO_PATTERN,
    # XXXHandler and BUG_URL are names, not notes. Case-sensitive for the same
    # reason - it drops TodoList and def todos() for free. Lookarounds rather
    # than consuming the boundary, or "TODO/FIXME" would report only the TODO.
    marker_re = re.compile(
        r"(?<![A-Za-z0-9_])(?P<mark>%s)(?![A-Za-z0-9_])" % "|".join(words)
    )

    files = git_files(root)
    in_git = files is not None
    if not in_git:
        files = walked_files(root)

    scopes = []
    for p in args.paths:
        full = Path(p) if os.path.isabs(p) else Path(root) / p
        scopes.append(os.path.relpath(str(full.resolve()), root))
    if scopes and set(scopes) != {"."}:
        files = [f for f in files
                 if any(f == s or f.startswith(s + os.sep) for s in scopes)]

    markers, skipped, rejected = [], Counter(), Counter()
    skipped_examples, scanned = defaultdict(list), 0

    for rel in sorted(files):
        reason = skip_reason(root, rel)
        if not reason:
            text, reason = read_text(os.path.join(root, rel))
            if text is not None:
                # Only files that mention a marker at all pay for the scanner.
                if not marker_re.search(text):
                    scanned += 1
                    continue
                reason = content_skip(rel, text)
        if reason:
            skipped[reason] += 1
            if len(skipped_examples[reason]) < 5:
                skipped_examples[reason].append(rel)
            continue
        scanned += 1
        found, rej = scan_file(rel, text, marker_re)
        markers += found
        rejected += rej

    if in_git and not args.no_blame and markers:
        attach_blame(root, markers)

    markers.sort(key=lambda m: (m["path"], m["line"]))
    result = {
        "root": root,
        "git": in_git,
        "counts": {
            "files_scanned": scanned,
            "files_skipped": sum(skipped.values()),
            "markers": len(markers),
            "rejected_not_comment": sum(rejected.values()),
            "prose": sum(1 for m in markers if m["context"] == "prose"),
            "guessed_syntax": sum(1 for m in markers if m["syntax"] == "guessed"),
        },
        "skipped": {k: {"files": v, "examples": skipped_examples[k]}
                    for k, v in skipped.most_common()},
        "rejected": dict(rejected),
        "by_marker": Counter(m["marker"] for m in markers).most_common(),
        "clusters": cluster(markers),
        "markers": markers,
    }

    if not args.text:
        json.dump(result, sys.stdout, indent=2)
        sys.stdout.write("\n")
        return

    c = result["counts"]
    print(f"{c['markers']} markers in {c['files_scanned']} files "
          f"({c['files_skipped']} files skipped, "
          f"{c['rejected_not_comment']} hits rejected as not-a-comment)")
    if not in_git:
        print("not a git repo: no age or author, and ignored paths are only "
              "excluded by name", file=sys.stderr)

    print("\n--- by marker ---")
    for name, n in result["by_marker"]:
        print(f"{n:>5}  {name}")

    print(f"\n--- clusters ({len(result['clusters'])}) ---")
    for cl in result["clusters"]:
        print(f"{cl['count']:>5}x in {cl['files']} files  {cl['example'][:90]}")
        for site in cl["sites"][:6]:
            print(f"         {site}")

    print(f"\n--- markers ({len(markers)}) ---")
    for mk in markers:
        age = f"{mk['age_days']}d" if mk.get("age_days") is not None else "-"
        flag = "" if mk["context"] == "code" else f" [{mk['context']}]"
        print(f"{mk['path'] + ':' + str(mk['line']):<34} {age:>6}  "
              f"{mk['note'][:100]}{flag}")

    if result["skipped"]:
        print("\n--- skipped ---")
        for reason, info in result["skipped"].items():
            print(f"{info['files']:>5}  {reason}: {', '.join(info['examples'][:3])}")


if __name__ == "__main__":
    main()
